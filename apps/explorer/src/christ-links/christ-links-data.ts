/**
 * - `jesus`: a prophecy of Christ and its fulfilment, or a figure of Christ Himself.
 * - `prophecy`: a prediction fulfilled later in the Bible's history (kings, nations, Jerusalem, John
 *   the Baptist, Pentecost…).
 * - `symbol`: a figure of something other than Christ Himself: the Virgin, the Church, baptism, the
 *   Eucharist, the Christian life, heaven.
 */
