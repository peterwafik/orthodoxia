export type UiKey = keyof typeof UI_LINES;
export type Ui = Readonly<Record<UiKey, string>>;

export function ui(locale: Locale): Ui {
  return Object.fromEntries(Object.entries(UI_LINES).map(([key, line]) => [key, line[locale]])) as Ui;
}

export const fill = (text: string, values: Record<string, string | number>): string =>
  text.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ''));
