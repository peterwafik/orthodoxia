/**
 * Writes docs/apologetics/COVERAGE.md: counts and lists of sources, questions and articles, with the human-review
 * dependencies and unresolved links. Run `npm run apologetics:coverage`.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { readFileSync, readdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { QUESTIONS } from '../../apps/web/src/data/apologetics/questions.ts';
import { SOURCES } from '../../apps/web/src/data/apologetics/sources.ts';
import type { Article } from '../../apps/web/src/data/apologetics/types.ts';

const ROOT = resolve(import.meta.dirname, '../..');
const dir = resolve(ROOT, 'apps/web/src/data/apologetics');
const articleFiles = readdirSync(resolve(dir, 'articles')).filter((f) => f.endsWith('.ts') && f !== 'index.ts');
const articles: Article[] = [];
for (const file of articleFiles) articles.push(((await import(pathToFileURL(resolve(dir, 'articles', file)).href)) as { article: Article }).article);
const link = JSON.parse(readFileSync(resolve(dir, 'link-report.json'), 'utf8')) as Record<string, { status: string; note?: string }>;

const by = <T,>(items: T[], key: (item: T) => string): Record<string, number> =>
  items.reduce<Record<string, number>>((acc, item) => ({ ...acc, [key(item)]: (acc[key(item)] ?? 0) + 1 }), {});
const list = (rec: Record<string, number>): string => Object.entries(rec).map(([k, v]) => `- ${k}: ${v}`).join('\n');
const cited = new Map<string, string[]>();
for (const a of articles) for (const id of new Set([...a.evidence.map((e) => e.sourceId), ...a.furtherReading])) cited.set(id, [...(cited.get(id) ?? []), a.id]);

const unresolved = SOURCES.filter((s) => (link[s.id]?.status ?? 'not_checked') !== 'ok' && s.url.startsWith('https://'));
const answered = new Set(articles.map((a) => a.questionId));

const out = `# Faith & Evidence: content coverage

Generated by \`npm run apologetics:coverage\`. Do not edit by hand.

## Sources (${SOURCES.length})

- Discovered: ${SOURCES.length}
- Metadata verified by an editor: ${SOURCES.filter((s) => s.review !== 'discovered').length}
- Full text reviewed by an editor: ${SOURCES.filter((s) => ['extracted', 'fact_checked', 'theological_reviewed', 'language_reviewed', 'published'].includes(s.review)).length}
- Metadata only (including awaiting copy): ${SOURCES.filter((s) => ['metadata_only', 'awaiting_copy', 'abstract_only'].includes(s.access)).length}
- Rights or access blocked / awaiting an authorised copy: ${SOURCES.filter((s) => ['awaiting_copy', 'paywalled', 'unavailable'].includes(s.access)).map((s) => s.id).join(', ') || 'none'}

By access state:
${list(by([...SOURCES], (s) => s.access))}

By kind:
${list(by([...SOURCES], (s) => s.kind))}

## Questions (${QUESTIONS.length})

- With a written draft: ${articles.filter((a) => a.state !== 'published').length}
- Published (named human reviewer): ${articles.filter((a) => a.state === 'published').length}
- Backlog (no article): ${QUESTIONS.filter((q) => !answered.has(q.id)).length}
- Backlog questions with no source lead (source gap): ${QUESTIONS.filter((q) => !answered.has(q.id) && q.leads.length === 0).length}

## Articles

${articles.map((a) => `- ${a.id}: ${a.state}, revision ${a.revision}, ${a.evidence.length} evidence entries, ${a.claims.length} claims, reviewers: ${a.reviewers.length === 0 ? 'none yet (human review required)' : a.reviewers.map((r) => r.name).join(', ')}`).join('\n')}

## Human-review dependencies

Every draft above needs: a historian or subject reviewer (facts and citations), a Coptic Orthodox theological reviewer, and a native Arabic language reviewer. The Mary article also needs the source gaps closed (see its "disputed" section).

## Source-to-article map

${[...cited.entries()].sort().map(([id, ids]) => `- ${id}: ${ids.join(', ')}`).join('\n')}

## Unresolved links (not yet confirmed reachable)

${unresolved.map((s) => `- ${s.id} ${s.url}: ${link[s.id]?.status ?? 'not checked'}${link[s.id]?.note === undefined ? '' : ` (${link[s.id]?.note})`}`).join('\n') || 'none'}

## Missing translations

Arabic and English are written together for every article; no machine translation is published. Arabic still needs native review.
`;

writeFileSync(resolve(ROOT, 'docs/apologetics/COVERAGE.md'), out);
console.log(`COVERAGE.md: ${articles.length} articles, ${unresolved.length} links not confirmed`);
